#!/usr/bin/env python3
"""vst/params.json -> src/params_gen.h: the parameter table of the native front end (src/Profit5Plugin.cpp).

The VST order is the released 0.2.1 wrapper build's: the 64 keys of vst/params.json, which must equal vst/params.lock (checked here;
tests/check_lock.sh checks the lock against the released build itself). 0.2.1 had no hidden popup flags, so nothing is reserved.
New parameters are appended after index 63 (vst/params.lock lists them too). Append only:
  64 fav_add, 65 fav_del   +FAV / -FAV: save the current sound as a favourite in the PRESET menu, delete the picked one (plugin-local)
  66 fav_name               the name being typed (text readout)
  67 kb_open                the drawn keyboard is showing (1) or not (0): the skin shows it with IndexedEnabling
  68.. kb_*                 the keyboard's keys (momentary): 0-9, A-Z, -, space, delete, shift, cancel, save
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]
LOCK = [l.strip() for l in open(os.path.join(ROOT, "vst", "params.lock")) if l.strip() and not l.startswith("#")]

keys = [p["key"] for p in P]
KB_CHARS = "1234567890QWERTYUIOPASDFGHJKLZXCVBNM-"
KB_KEYS = [("kb_" + ("dash" if c == "-" else c.lower()), "Key " + c) for c in KB_CHARS] + \
          [("kb_space", "Key Space"), ("kb_bksp", "Key Delete"), ("kb_shift", "Key Shift"), ("kb_cancel", "Key Cancel"), ("kb_save", "Key Save")]
APPENDED = [("fav_add", "+ Favourite"), ("fav_del", "- Favourite"), ("fav_name", "Favourite Name"), ("kb_open", "Keyboard")] + KB_KEYS
FAV_SLOTS = 32
if keys + [k for k, _ in APPENDED] != LOCK:
    raise SystemExit("vst/params.json no longer matches vst/params.lock: the order is frozen (append only)")
idx = {k: i for i, k in enumerate(keys)}

FL = dict(kUi=32, kLocal=16, kMomentary=1, kText=2, kChoice=8, kStep=128, kNoAuto=512, kPolled=1024, kInt=2048, kFloat=4096, kPreset=8192)
out = ["/* generated by tools/gen_native_params.py from vst/params.json: do not edit. One row per parameter, in the frozen VST order. */",
       "#pragma once",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; int stepTarget; float stepDelta; };",
       ""]
rows = []


def F(v):
    t = "%g" % v
    return t + ("f" if ("." in t or "e" in t) else ".0f")


for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n, st, sd = 0, "nullptr", 0, -1, 0.0
    if "options" in p:
        fl |= FL["kChoice"] | FL["kPolled"]
        opts = p["options"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        lo, hi, d = 0, len(opts) - 1, opts.index(p["default"]) if isinstance(p["default"], str) else p["default"]
    elif p.get("momentary"):
        fl |= FL["kMomentary"] | FL["kNoAuto"]
        lo, hi, d = 0, 1, 0
        if p.get("step_of"):
            fl |= FL["kStep"]
            st, sd = idx[p["step_of"]], p.get("step_delta", 1)
    elif p.get("display") == "string":
        fl |= FL["kText"] | FL["kNoAuto"]                       # readouts: the value is a change counter
        lo, hi, d = 0, 1023, 0
    else:
        lo, hi, d = p["min"], p["max"], p["default"]
        fl |= FL["kPolled"] | (FL["kInt"] if p.get("display") == "int" else FL["kFloat"])
        if k == "preset":
            fl |= FL["kPreset"]
    rows.append("    {%s, %s, %s, %s, %s, %d, %s, %d, %d, %s}," % (json.dumps(k), json.dumps(p["name"]), F(lo), F(hi), F(d), fl, ch, n, st, F(sd)))

for k, n in APPENDED:
    fl, hi = FL["kLocal"] | FL["kMomentary"] | FL["kNoAuto"], 1
    if k == "fav_name":
        fl, hi = FL["kLocal"] | FL["kText"] | FL["kNoAuto"], 1023
    elif k == "kb_open":
        fl = FL["kLocal"] | FL["kUi"] | FL["kNoAuto"]
    rows.append("    {%s, %s, 0.0f, %s, 0.0f, %d, nullptr, 0, -1, 0.0f}," % (json.dumps(k), json.dumps(n), F(hi), fl))
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumParams = %d;" % (len(P) + len(APPENDED)),
        "static const int kFavAdd = %d, kFavDel = %d, kFavSlots = %d;" % (len(P), len(P) + 1, FAV_SLOTS),
        "static const int kFavName = %d, kKbOpen = %d, kKbFirst = %d, kKbCount = %d;" % (len(P) + 2, len(P) + 3, len(P) + 4, len(KB_KEYS)),
        "static const char kKbChars[] = %s;   // the character keys, in order from kKbFirst (then space, delete, shift, cancel, save)" % json.dumps(KB_CHARS),
        "static const int kFavNameMax = 20;",
        "static const int kNumEngineParams = %d;   // 0 .. this - 1 are the engine's keys" % len(P),
        "static const int kPresetParam = %d;" % idx["preset"],
        "static const int kPresetSlots = %d;     // programs in the PRESET menu (src/plugin.c P5_SLOTS)" % (P[idx["preset"]]["max"] + 1), ""]
open(os.path.join(ROOT, "src", "params_gen.h"), "w").write("\n".join(out))
print("src/params_gen.h: %d params, %d programs + %d favourites" % (len(P) + len(APPENDED), P[idx["preset"]]["max"] + 1, FAV_SLOTS))
