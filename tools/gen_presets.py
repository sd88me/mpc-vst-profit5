#!/usr/bin/env python3
"""Generate src/presets_factory.h from tools/factory_sheets.txt.

factory_sheets.txt is a hand transcription of the 1978 factory patch sheets (knob pointers read to about +-0.5 on the 0-10
scale, switches as drawn). Each line: name | fields grouped as in the header comment of that file. Dials become 0..1;
the two oscillator frequency knobs become semitones (the firmware halves them to 60 semitone steps over 0-10, manual 3.3)."""
import sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'factory_sheets.txt')
OUT = os.path.join(HERE, '..', 'src', 'presets_factory.h')

def bits(s):
    return [c == '1' for c in s]

def parse():
    """[(name, [24 pot values 0..1 / semitones], switch bits)] in sheet order."""
    rows = []
    for line in open(SRC):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        g = [x.strip().split() for x in line.split('|')]
        name = ' '.join(g[0])
        pmfe, pmob, pmd = float(g[1][0]), float(g[1][1]), bits(g[1][2])
        afreq, ash, apw, sync = float(g[2][0]), bits(g[2][1]), float(g[2][2]), g[2][3] == '1'
        lfof, lsh = float(g[3][0]), bits(g[3][1])
        wmix, wmd = float(g[4][0]), bits(g[4][1])
        bfreq, bfine, bsh, bpw, blo, bkbd = float(g[5][0]), float(g[5][1]), bits(g[5][2]), float(g[5][3]), g[5][4] == '1', g[5][5] == '1'
        glide = float(g[6][0])
        ma, mb, mn = map(float, g[7])
        cut, res, env, fkbd = float(g[8][0]), float(g[8][1]), float(g[8][2]), g[8][3] == '1'
        fa, fd, fs, fr = map(float, g[9])
        aa, ad, as_, ar = map(float, g[10])
        rel = g[11][0] == '1'
        uni = g[12][0] == '1'
        semis = lambda d: max(0, min(60, round(d * 6)))
        d = lambda v: round(max(0.0, min(10.0, v)) / 10, 3)
        sw = 0
        for i, b in enumerate(pmd + ash + [sync] + lsh + wmd + bsh + [blo, bkbd, fkbd, rel, uni]):
            sw |= b << i
        rows.append((name, [d(pmfe), d(pmob), semis(afreq), d(apw), d(lfof), d(wmix), semis(bfreq), d(bfine), d(bpw), d(glide),
                            d(ma), d(mb), d(mn), d(cut), d(res), d(env), d(fa), d(fd), d(fs), d(fr), d(aa), d(ad), d(as_), d(ar)], sw))
    return rows


def main():
    rows = parse()
    with open(OUT, 'w') as f:
        f.write('/* Generated by tools/gen_presets.py from tools/factory_sheets.txt: do not edit. */\n#pragma once\n#include <stdint.h>\n\n')
        f.write('/* switch bits, low to high */\nenum {\n')
        names = ['PM_FREQ_A', 'PM_PW_A', 'PM_FILTER', 'A_SAW', 'A_PULSE', 'A_SYNC', 'LFO_SAW', 'LFO_TRI', 'LFO_SQUARE',
                 'WM_FREQ_A', 'WM_FREQ_B', 'WM_PW_A', 'WM_PW_B', 'WM_FILTER', 'B_SAW', 'B_TRI', 'B_PULSE', 'B_LO', 'B_KBD',
                 'F_KBD', 'RELEASE', 'UNISON']
        for i, n in enumerate(names):
            f.write('    P5S_%s = 1u << %d,\n' % (n, i))
        f.write('};\n\n/* dials 0..1 except a_semis / b_semis (0..60) */\ntypedef struct {\n    const char *name;\n'
                '    float pm_fenv, pm_oscb; int a_semis; float a_pw, lfo_freq, wm_mix; int b_semis; float b_fine, b_pw, glide;\n'
                '    float mix_a, mix_b, mix_noise, cutoff, reso, env_amt, f_a, f_d, f_s, f_r, a_a, a_d, a_s, a_r;\n'
                '    uint32_t sw;\n} p5_sheet_t;\n\n')
        f.write('static const p5_sheet_t P5_FACTORY[%d] = {\n' % len(rows))
        for name, v, sw in rows:
            f.write('    { "%s", %s, 0x%06xu },\n' % (name.replace('"', ''), ', '.join(repr(x) if isinstance(x, int) else ('%.4g' % x if '.' in ('%.4g' % x) else '%.4g.0' % x) + 'f' for x in v), sw))
        f.write('};\n')
    print('%d programs -> %s' % (len(rows), os.path.relpath(OUT)))

if __name__ == '__main__':
    sys.exit(main())
