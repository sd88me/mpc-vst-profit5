#!/usr/bin/env python3
"""Generate vst/params.json and src/plugin_keys.h from one list (the engine's P5P_* order, then the plugin's own "preset").

The VST parameter order is the engine's enum order and is append-only once released (params.lock, mpc-vst-plugins PR 488).
Every parameter maps linearly onto the engine's 0..1 value: norm = (v - min) / (max - min); an option's index counts as v.
Defaults are program 1-1 of tools/factory_sheets.txt, so the plugin opens on the first factory program."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_presets  # noqa: E402

OFF_ON = ["Off", "On"]
# key, name, kind (pot: 0..10, semis: 0..60, sw: Off/On, or ("opts", [...]), ("int", lo, hi)), engine enum
P = [
    ("pm_fenv", "PM Filt Env", "pot"), ("pm_oscb", "PM Osc B", "pot"), ("a_freq", "A Frequency", "semis"), ("a_pw", "A Pulse W", "pot"),
    ("lfo_freq", "LFO Freq", "pot"), ("wm_mix", "WM Mix", "pot"), ("b_freq", "B Frequency", "semis"), ("b_fine", "B Fine", "pot"),
    ("b_pw", "B Pulse W", "pot"), ("glide", "Glide", "pot"), ("mix_a", "Mix Osc A", "pot"), ("mix_b", "Mix Osc B", "pot"),
    ("mix_noise", "Mix Noise", "pot"), ("cutoff", "Cutoff", "pot"), ("reso", "Resonance", "pot"), ("env_amt", "Env Amount", "pot"),
    ("f_attack", "F Attack", "pot"), ("f_decay", "F Decay", "pot"), ("f_sustain", "F Sustain", "pot"), ("f_release", "F Release", "pot"),
    ("a_attack", "A Attack", "pot"), ("a_decay", "A Decay", "pot"), ("a_sustain", "A Sustain", "pot"), ("a_release", "A Release", "pot"),
    ("pm_freq_a", "PM Freq A", "sw"), ("pm_pw_a", "PM PW A", "sw"), ("pm_filter", "PM Filter", "sw"), ("a_saw", "A Saw", "sw"),
    ("a_pulse", "A Pulse", "sw"), ("a_sync", "Sync", "sw"), ("lfo_saw", "LFO Saw", "sw"), ("lfo_tri", "LFO Tri", "sw"),
    ("lfo_square", "LFO Square", "sw"), ("wm_freq_a", "WM Freq A", "sw"), ("wm_freq_b", "WM Freq B", "sw"), ("wm_pw_a", "WM PW A", "sw"),
    ("wm_pw_b", "WM PW B", "sw"), ("wm_filter", "WM Filter", "sw"), ("b_saw", "B Saw", "sw"), ("b_tri", "B Tri", "sw"),
    ("b_pulse", "B Pulse", "sw"), ("b_lo", "B Lo Freq", "sw"), ("b_kbd", "B Keyboard", "sw"), ("f_kbd", "F Keyboard", "sw"),
    ("release", "Release", "sw"), ("unison", "Unison", "sw"),
    ("rev", "Rev", ("opts", ["Rev 2", "Rev 4"])), ("vintage", "Vintage", "pot"), ("vel_filter", "Vel Filter", "pot"),
    ("vel_amp", "Vel Amp", "pot"), ("at_filter", "AT Filter", "pot"), ("at_lfo", "AT LFO", "pot"),
    ("tune", "Master Tune", ("int", -50, 50)), ("volume", "Volume", "pot"), ("voices", "Voices", ("int", 1, 5)),
    ("quality", "Quality", ("opts", ["Eco", "High"])), ("lfo_init", "LFO Initial", "pot"), ("kbd_half", "Kbd Track", ("opts", ["Full", "Half"])),
]
NENGINE = len(P)


def spec(kind):
    if kind == "pot": return 0, 10, None
    if kind == "semis": return 0, 60, None
    if kind == "sw": return 0, 1, OFF_ON
    if kind[0] == "opts": return 0, len(kind[1]) - 1, kind[1]
    return kind[1], kind[2], None


def main():
    name0, pots0, sw0 = gen_presets.parse()[0]
    names = [r[0] for r in gen_presets.parse()]
    norm0 = {k: None for k, _, _ in P}
    for i, (k, _, kind) in enumerate(P[:24]):
        norm0[k] = pots0[i] / 60 if kind == "semis" else pots0[i]
    for b in range(22):
        norm0[P[24 + b][0]] = float((sw0 >> b) & 1)
    norm0.update(rev=0, vintage=0.6, vel_filter=0, vel_amp=0, at_filter=0, at_lfo=0, tune=0.5, volume=0.8, voices=1, quality=1, lfo_init=0, kbd_half=0)
    out = []
    for k, name, kind in P:
        lo, hi, opts = spec(kind)
        v = lo + norm0[k] * (hi - lo)
        e = {"key": k, "name": name}
        if opts:
            e["options"] = opts
            e["default"] = opts[int(round(v))]
        else:
            e.update(min=lo, max=hi, default=round(v, 2) if kind == "pot" else int(round(v)))
            e["display"] = "int" if kind != "pot" else None
            if kind == "pot":
                del e["display"]
        out.append(e)
    out.append({"key": "preset", "name": "Program", "options": names, "default": names[0]})
    here = os.path.join(HERE, "..")
    json.dump({"name": "Profit-5", "params": out}, open(os.path.join(here, "vst", "params.json"), "w"), indent=1)
    with open(os.path.join(here, "src", "plugin_keys.h"), "w") as f:
        f.write("/* Generated by tools/gen_params.py: do not edit. VST order = engine order (P5P_*), then the plugin's \"preset\". */\n")
        f.write("#pragma once\n#include \"p5_engine.h\"\n\ntypedef struct { const char *key; float lo, hi; int nopts; } p5_key_t;\n\n")
        f.write("static const p5_key_t P5_KEYS[%d] = {\n" % NENGINE)
        for k, name, kind in P:
            lo, hi, opts = spec(kind)
            f.write("    { \"%s\", %g, %g, %d },\n" % (k, lo, hi, len(opts) if opts else 0))
        f.write("};\n_Static_assert(sizeof P5_KEYS / sizeof *P5_KEYS == P5P_COUNT, \"tools/gen_params.py and engine.h disagree\");\n")
    print("%d params (+ preset, %d programs) -> vst/params.json, src/plugin_keys.h" % (NENGINE, len(names)))


if __name__ == "__main__":
    main()
