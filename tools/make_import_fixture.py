    f.write("static const char FIX_BRASS[] =\n")
    for line in BRASS.split("\n")[:-1]:
        f.write('    "%s\\n"\n' % "".join(c if 32 <= ord(c) < 127 and c not in '"\\\\' else "\\%03o" % ord(c) for c in line))
    f.write(";\n")
    f.write(carray("FIX_ZIP", z))
