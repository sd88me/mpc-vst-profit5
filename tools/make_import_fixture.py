FOREIGN = BRASS.replace("#AM=Repro-5", "#AM=Diva")


def zip_of(files):
    out, cd = b"", b""
    for name, data, method in files:
        comp = zlib.compressobj(9, zlib.DEFLATED, -15).compress(data)
        c = zlib.compressobj(9, zlib.DEFLATED, -15)
        comp = c.compress(data) + c.flush() if method == 8 else data
        crc = zlib.crc32(data) & 0xFFFFFFFF
        nm = name.encode()
        hdr = struct.pack("<IHHHHHIIIHH", 0x04034B50, 20, 0, method, 0, 0x21, crc, len(comp), len(data), len(nm), 0)
        cd += struct.pack("<IHHHHHHIIIHHHHHII", 0x02014B50, 20, 20, 0, method, 0, 0x21, crc, len(comp), len(data), len(nm), 0, 0, 0, 0, 0, len(out)) + nm
        out += hdr + nm + comp
    end = struct.pack("<IHHHHIIH", 0x06054B50, 0, 0, len(files), len(files), len(cd), len(out), 0)
    return out + cd + end


def carray(name, b):
    rows = [", ".join("0x%02x" % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return "static const unsigned char %s[%d] = {\n    %s\n};\n" % (name, len(b), ",\n    ".join(rows))


z = zip_of([("bank/Test Brass.h2p", BRASS.encode("latin-1"), 8), ("bank/Inverted Env.h2p", INVERTED.encode("latin-1"), 0),
            ("bank/Foreign.h2p", FOREIGN.encode("latin-1"), 8), ("bank/readme.txt", b"not a patch", 8)])
